import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { defaultDocs, docsSchema, isDocsPublic, publicDocs } from "../src/lib/docs/model";
async function main() {
  process.env.DATABASE_URL = ""; process.env.POSTGRES_URL = ""; process.env.VERCEL = "";
  process.env.DATABASE_DIR = mkdtempSync(join(tmpdir(), "foodbridge-docs-"));
  process.env.DEMO_MODE = "false";
  const { readDocs, writeDocs, docsMetrics } = await import("../src/lib/docs/service");
  const { GET } = await import("../src/app/api/docs/route");
  const now = new Date("2026-11-20T12:00:00Z");
  assert.equal(isDocsPublic(defaultDocs, now), false);
  const content = { ...defaultDocs, enabled: true, startsAt: "2026-11-20T12:00:00Z", endsAt: "2026-11-20T13:00:00Z" };
  assert.equal(isDocsPublic(content, now), true);
  assert.equal(isDocsPublic(content, new Date("2026-11-20T11:59:59Z")), false);
  assert.equal(isDocsPublic(content, new Date(content.endsAt)), false);
  assert.equal(docsSchema.safeParse({ ...content, endsAt: content.startsAt }).success, false);
  assert.equal(docsSchema.safeParse({ ...defaultDocs, sections: [defaultDocs.sections[0], defaultDocs.sections[0]] }).success, false);
  assert.equal((await GET()).status, 404);
  const visible = { ...defaultDocs, enabled: true, sections: [{ ...defaultDocs.sections[0], visible: false }, defaultDocs.sections[1]] };
  assert.equal(await writeDocs(visible, 0), true);
  assert.equal(await writeDocs(defaultDocs, 0), false);
  const response = await GET(); assert.equal(response.status, 200);
  assert.equal((await response.json()).content.sections.length, 1);
  const before = await docsMetrics();
  const { getDb } = await import("../src/db");
  const { users } = await import("../src/db/schema");
  await (await getDb()).insert(users).values({ role: "donor", name: "Docs test", email: "docs@test.local", phone: "private", passwordHash: "fixture" });
  assert.equal((await docsMetrics()).users, before.users + 1);
  assert.equal(await writeDocs({ ...visible, title: "Updated immediately" }, 1), true);
  assert.equal((await readDocs()).content.title, "Updated immediately");
  assert.equal(await writeDocs(defaultDocs, 1), false);
  assert.equal(await writeDocs(defaultDocs, 2), true);
  assert.equal((await GET()).status, 404);
  assert.equal(publicDocs({ ...defaultDocs, showTeam: false, team: [{ id: crypto.randomUUID(), name: "Private", role: "Member", email: "private@test.local", image: "" }] }).team.length, 0);
  console.log("PASS: default OFF, public ON, schedule boundaries, invalid dates, revisions, persistence, hidden content, live database metrics and public API gate");
}
main().then(() => process.exit(0), (error) => { console.error(error); process.exit(1); });
